import { publicDuelReward } from "../domain/publicDuelReward";
import { hasPlaytestRules, hasRevisedNightRules } from "../domain/config";

type GuideSection = {
  title: string;
  ordered?: boolean;
  items?: { label: string; text: string }[];
  paragraphs?: string[];
};

export function ruleGuide(rulesVersion: string): GuideSection[] {
  const rules = { rulesVersion };
  const revised = hasRevisedNightRules(rules);
  const trade = hasPlaytestRules(rules)
    ? "午前・午後の公開行動を終え、未回答の取引を解決すると判定に進みます。"
    : "午前・午後の公開行動が終わると、未回答の取引は失効し、判定に進みます。";
  const foresight = revised
    ? "予知を使った魔女が、候補から翌日の共通イベントを選びます。"
    : "予知の候補が2枚以上ある場合は、全員が匿名で1票を投じ、最多票の候補を採用します。同票なら最多票の候補から抽選します。";
  const dawn = revised
    ? "今日の課題を判定して翌日へ進みます。"
    : "今日の課題を判定し、夜明けの画面を確認してから「次の日へ」で進みます。";
  const raidReward = revised
    ? "襲撃の報酬では、相手の持ち物をランダムに1個奪うか、翌日の行動を制限するかを選びます。制限を受けた魔女が採集か研究を選びます。"
    : "襲撃の報酬では、相手の持ち物を選んで1個奪うか、翌日の採集か研究を指定するかを選びます。指定された研究に必要な素材がなければ採集に切り替わります。";

  return [
    {
      title: "ゲームの概要・目的",
      paragraphs: [
        "あなたとAIの魔女3人で、研究所の8日間を過ごします。毎日の共通イベントに協力しながら、自分の「今日の課題」と「卒業課題」に取り組みましょう。",
        "今日の課題を達成すると名声ポイント（FP）が増えます。8日間を終えたとき、卒業課題を達成した魔女が卒業し、その卒業者の中から首席が決まります。",
      ],
    },
    {
      title: "1日の流れ",
      ordered: true,
      items: [
        {
          label: "公開行動",
          text: "今日の課題と共通イベントを確認します。1日2AP（行動点）で、午前・午後の自分の手番ごとに、APを使う行動を1回まで行えます。",
        },
        {
          label: "共通イベントの判定",
          text: trade + "通算3回目の失敗なら、その場で全員敗北です。",
        },
        {
          label: "固有魔法と夜間行動",
          text:
            "固有魔法を使うか決めてから、夜間行動を1つ選びます。" +
            foresight +
            "結界は、自分かほかの魔女1人を選び、その夜、その魔女に向けられた襲撃・呪詛・偵察を防ぎます。錬金は夜間行動と一緒に行えます。",
        },
        {
          label: "夜の結果と夜明け",
          text:
            "必要に応じて秘匿決闘と報酬を処理します。その後、" +
            dawn +
            "第8日は卒業と首席を判定します。",
        },
      ],
    },
    {
      title: "基本システム",
      items: [
        {
          label: "素材と研究",
          text: "採集では基本2個の素材を獲得します。研究では対応する素材を使い、火・水・風の能力を伸ばします。購買部では基本3個の素材を好きな素材1個に交換できます。採集・研究・購買部は各1AP、魔女間取引と仮納品は0APです。",
        },
        {
          label: "共通イベント",
          text: "カードに書かれた条件を全員で満たします。素材や薬の納品、採集・研究の回数、模擬戦など、条件はカードごとに異なります。仮納品した品は、成功時に採用された分が消費され、失敗時には返却されます。",
        },
        {
          label: "夜間行動",
          text:
            "襲撃で相手に挑む、呪詛で翌日の行動を妨げる、警戒で偵察に備える、休息で翌日に備える、偵察で相手の夜間行動を調べる、の5つです。" +
            raidReward +
            "第8夜は強奪のみ選べます。",
        },
        {
          label: "決闘",
          text: "HP12で始まり、最大5ラウンド。火は風に、風は水に、水は火に有利です。双方のダメージを同時に反映します。片方だけHPが0になれば決着し、5ラウンドで決着しなければ残りHPの多い側が勝ちます。同時にHPが0になった場合や、5ラウンド終了時に残りHPが同じ場合は引き分けです。",
        },
      ],
    },
    {
      title: "名声ポイント（FP）",
      paragraphs: [
        `今日の課題を達成すると＋1FP、通常の公開決闘に勝つと${publicDuelReward({ rulesVersion, day: 5 }) === 2 ? "1〜4日目は＋1FP、5〜8日目は＋2FP" : "＋1FP"}です。共通イベントのFPは、カードごとの条件を満たした魔女に入ります。模擬戦や夜間決闘の勝利によるFP加算はありません。偵察のための戦闘に勝って情報を得ると、対象のFPが減ることがあります。`,
        "卒業者は最終FPの多い順に並びます。同点なら「今日の課題」の達成日数を比べ、それも同じなら同順位です。第8日のFPを参照する卒業課題には、同日の課題報酬を足す前のFPを使います。順位には報酬を足した後のFPを使います。",
      ],
    },
    {
      title: "エンディングと勝利条件",
      items: [
        {
          label: "研究所崩壊",
          text: "共通イベントに通算3回失敗すると、全員敗北です。その日の夜間行動と課題判定は行いません。",
        },
        {
          label: "未卒業",
          text: "研究所が存続して8日目を終えても、卒業課題が未達成なら未卒業です。",
        },
        {
          label: "卒業・首席",
          text: "卒業課題を達成すると卒業です。卒業者の順位が1位なら首席、1位が複数なら共同首席です。卒業者がいなければ首席もいません。",
        },
      ],
    },
    {
      title: "1日分のプレイ例",
      items: [
        {
          label: "今日の課題「星の収穫祭」",
          text: "その日の採集で、素材を合計2個以上獲得する。",
        },
        {
          label: "共通イベント「魔導書の整理整頓」",
          text: "魔女全員の採集・研究を合計4回以上成立させる。",
        },
      ],
      paragraphs: [
        "午前に採集して素材を2個獲得し、午後に手持ちの素材で火を研究します。ほかの魔女の行動と合わせて採集・研究が4回以上成立すれば、共通イベントは成功。あなたも貢献したので＋1FPを得ます。",
        "夜は休息を選び、襲撃されずに休息に成功したとします。夜明けには、昼の採集で条件を満たした「星の収穫祭」が達成となり、さらに＋1FP。休息の補正は翌日の公開行動に適用されます。",
      ],
    },
  ];
}
